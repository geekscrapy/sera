"""Ephemeral RAM-keyed AES-256-GCM spool manager (`<workspace>/.sera/spool/`)."""

from __future__ import annotations

import hashlib
import json
import os
from dataclasses import dataclass
from pathlib import Path

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from sera.core.models import RawEventEnvelope


NONCE_SIZE = 12


class SpoolTamperError(RuntimeError):
    """Raised when an encrypted spool batch fails AES-GCM authentication or SHA-256 verification."""


@dataclass(frozen=True)
class SpoolBatchHandle:
    """Metadata handle for an encrypted spool chunk stored on disk."""

    job_id: str
    slice_id: str
    sequence: int
    file_path: Path
    plaintext_sha256: str
    event_count: int


class EphemeralSpoolManager:
    """Encrypts and authenticates downloaded batches using an autogenerated in-memory 256-bit key.

    Security & Resume Contract:
    - `self._key` lives strictly in process RAM (`os.urandom(32)`).
    - Tampering with ciphertext, nonce, filename/AAD, or deleting/replacing files raises `SpoolTamperError`.
    - Across process restarts, orphaned `.enc` files cannot be decrypted and are purged via `purge_orphans()`;
      interrupted jobs resume cleanly at the slice level via `sera.sqlite`.
    """

    def __init__(self, spool_dir: Path, ram_key: bytes | None = None) -> None:
        self.spool_dir = spool_dir
        self.spool_dir.mkdir(parents=True, exist_ok=True)
        key = ram_key if ram_key is not None else os.urandom(32)
        if len(key) != 32:
            raise ValueError("AES-256-GCM key must be exactly 32 bytes")
        self._aesgcm = AESGCM(key)

    def purge_orphans(self) -> int:
        """Delete any un-uploaded `.enc` chunks left behind by previous terminated processes."""
        removed = 0
        for enc_file in self.spool_dir.glob("*.enc"):
            try:
                enc_file.unlink()
                removed += 1
            except OSError:
                pass
        return removed

    @staticmethod
    def _aad(job_id: str, slice_id: str, sequence: int, plaintext_sha256: str) -> bytes:
        return f"sera-v1|{job_id}|{slice_id}|{sequence}|{plaintext_sha256}".encode("utf-8")

    def write_batch(
        self,
        job_id: str,
        slice_id: str,
        sequence: int,
        events: list[RawEventEnvelope],
    ) -> SpoolBatchHandle:
        """Serialize events as NDJSON, compute SHA-256, encrypt with AES-256-GCM, and write `.enc`."""
        lines = [
            json.dumps(ev.to_destination_row(), ensure_ascii=False, separators=(",", ":"))
            for ev in events
        ]
        ndjson_bytes = ("\n".join(lines) + "\n").encode("utf-8")
        plaintext_sha256 = hashlib.sha256(ndjson_bytes).hexdigest()
        nonce = os.urandom(NONCE_SIZE)
        aad = self._aad(job_id, slice_id, sequence, plaintext_sha256)
        ciphertext = self._aesgcm.encrypt(nonce, ndjson_bytes, aad)

        safe_slice = slice_id.replace("/", "_")
        file_path = self.spool_dir / f"{job_id}_{safe_slice}_{sequence:05d}.enc"
        file_path.write_bytes(nonce + ciphertext)

        return SpoolBatchHandle(
            job_id=job_id,
            slice_id=slice_id,
            sequence=sequence,
            file_path=file_path,
            plaintext_sha256=plaintext_sha256,
            event_count=len(events),
        )

    def read_and_verify(self, handle: SpoolBatchHandle) -> bytes:
        """Read `.enc` chunk, authenticate via AES-256-GCM + AAD, and verify SHA-256 digest."""
        if not handle.file_path.exists():
            raise SpoolTamperError(f"Spool batch missing on disk: {handle.file_path}")
        blob = handle.file_path.read_bytes()
        if len(blob) <= NONCE_SIZE + 16:
            raise SpoolTamperError(f"Spool batch truncated or corrupt: {handle.file_path}")

        nonce = blob[:NONCE_SIZE]
        ciphertext = blob[NONCE_SIZE:]
        aad = self._aad(handle.job_id, handle.slice_id, handle.sequence, handle.plaintext_sha256)
        try:
            plaintext = self._aesgcm.decrypt(nonce, ciphertext, aad)
        except InvalidTag as exc:
            raise SpoolTamperError(
                f"AES-256-GCM authentication failed for spool batch '{handle.file_path.name}'"
            ) from exc

        actual_sha256 = hashlib.sha256(plaintext).hexdigest()
        if actual_sha256 != handle.plaintext_sha256:
            raise SpoolTamperError(
                f"SHA-256 mismatch for spool batch '{handle.file_path.name}': "
                f"expected {handle.plaintext_sha256}, got {actual_sha256}"
            )
        return plaintext

    @staticmethod
    def remove(handle: SpoolBatchHandle) -> None:
        """Delete spool file once destination commit succeeds."""
        try:
            handle.file_path.unlink(missing_ok=True)
        except OSError:
            pass
